#!/usr/bin/env node
// Reads frontmatter + body of every content/posts and content/projects MDX,
// then writes src/lib/content-index.generated.ts with:
//   - the posts[] array (translatable title/excerpt merged across pt-BR/en/es)
//   - the projects[] array (translatable linkLabel/summary/problem/decision/result/repos.label)
//   - computed reading time (words / 200 wpm, ceil, min 1)
//
// This file is the single source of truth consumed by src/lib/data.ts.
// Edit content/<kind>/<slug>.<locale>.mdx, run this script, commit both.

import matter from 'gray-matter';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const WORDS_PER_MINUTE = 200;
const locales = ['pt-BR', 'en', 'es'];
const defaultLocale = 'pt-BR';
const root = resolve(process.cwd());
const postsDir = join(root, 'content/posts');
const projectsDir = join(root, 'content/projects');
const output = join(root, 'src/lib/content-index.generated.ts');

const required = (value, path) => {
	if (value === undefined || value === null) {
		throw new Error(`Missing required field "${path}"`);
	}
	return value;
};

const stripJsxBlocks = (text) =>
	text
		.replace(/<Snippet[\s\S]*?<\/Snippet>/g, '')
		.replace(/<Callout[\s\S]*?<\/Callout>/g, '')
		.replace(/```[\s\S]*?```/g, '')
		.replace(/`[^`]+`/g, '');

const countWords = (text) =>
	text
		.split(/\s+/)
		.filter((token) => /[a-zA-ZÀ-ÿ0-9]/.test(token)).length;

const groupBySlug = (dir, suffix) => {
	const result = new Map();
	for (const file of readdirSync(dir)) {
		const match = file.match(new RegExp(`^(.+)\\.(${locales.join('|')})\\.mdx$`));
		if (!match) continue;
		const [, slug, locale] = match;
		if (!result.has(slug)) result.set(slug, new Map());
		const parsed = matter(readFileSync(join(dir, file), 'utf8'));
		result.get(slug).set(locale, parsed);
	}
	return result;
};

const translatedField = (bySlug, key, slug) => {
	const translated = {};
	for (const locale of locales) {
		const data = bySlug.get(locale)?.data ?? bySlug.get(defaultLocale)?.data;
		if (!data) continue;
		translated[locale] = required(data[key], `${slug}.${locale}.${key}`);
	}
	return translated;
};

const readingMinutes = (bySlug) => {
	const defaultEntry = bySlug.get(defaultLocale);
	if (!defaultEntry) return 1;
	const prose = stripJsxBlocks(defaultEntry.content);
	const words = countWords(prose);
	return Math.max(1, Math.ceil(words / WORDS_PER_MINUTE));
};

const buildPosts = () => {
	const grouped = groupBySlug(postsDir);
	const posts = [];
	for (const [slug, bySlug] of grouped) {
		const def = bySlug.get(defaultLocale);
		if (!def) throw new Error(`Missing ${defaultLocale} MDX for post "${slug}"`);
		const d = def.data;
		posts.push({
			id: slug,
			cat: required(d.cat, `${slug}.cat`),
			dateIso: required(d.dateIso, `${slug}.dateIso`),
			min: readingMinutes(bySlug),
			title: translatedField(bySlug, 'title', slug),
			excerpt: translatedField(bySlug, 'excerpt', slug),
			teaser: d.teaser ?? null,
		});
	}
	posts.sort((a, b) => (a.dateIso < b.dateIso ? 1 : -1));
	return posts;
};

const buildProjects = () => {
	const grouped = groupBySlug(projectsDir);
	const projects = [];
	for (const [slug, bySlug] of grouped) {
		const def = bySlug.get(defaultLocale);
		if (!def) throw new Error(`Missing ${defaultLocale} MDX for project "${slug}"`);
		const d = def.data;
		const defRepos = Array.isArray(d.repos) ? d.repos : [];
		const repos = defRepos.map((repo, index) => ({
			url: required(repo.url, `${slug}.repos[${index}].url`),
			label: Object.fromEntries(
				locales.map((locale) => {
					const data = bySlug.get(locale)?.data ?? d;
					const repoAtLocale = Array.isArray(data.repos)
						? data.repos[index]
						: null;
					return [
						locale,
						required(
							repoAtLocale?.label ?? repo.label,
							`${slug}.repos[${index}].label.${locale}`,
						),
					];
				}),
			),
		}));
		projects.push({
			id: slug,
			name: required(d.name, `${slug}.name`),
			year: required(d.year, `${slug}.year`),
			tech: required(d.tech, `${slug}.tech`),
			link: required(d.link, `${slug}.link`),
			tags: required(d.tags, `${slug}.tags`),
			linkLabel: translatedField(bySlug, 'linkLabel', slug),
			summary: translatedField(bySlug, 'summary', slug),
			problem: translatedField(bySlug, 'problem', slug),
			decision: translatedField(bySlug, 'decision', slug),
			result: translatedField(bySlug, 'result', slug),
			repos,
		});
	}
	return projects;
};

const header = `// AUTO-GENERATED by scripts/build-content-index.mjs — do not edit by hand.
// Run \`pnpm run content:build\` after changing files under content/.
import type { Post, Project } from './data';
`;

const emit = (posts, projects) =>
	`${header}
export const postsIndex: Post[] = ${JSON.stringify(posts, null, 2)};

export const projectsIndex: Project[] = ${JSON.stringify(projects, null, 2)};
`;

const posts = buildPosts();
const projects = buildProjects();
writeFileSync(output, emit(posts, projects));
console.log(
	`Content index written: ${posts.length} posts, ${projects.length} projects.`,
);
